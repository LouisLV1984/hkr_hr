"""Run synthetic unittest fixtures in per-app schemas of a disposable local cluster.

Never use a shared/runtime cluster. The actual PostgreSQL data_directory must
match --data-directory and be below this application's ignored tmp directory.
Set HKR_HR_TEST_DATABASE_URL to a local PostgreSQL URL for hkr_hr_db first.
"""
import argparse
import os
from pathlib import Path
import sys
import unittest
import uuid

import psycopg
from psycopg import sql
from sqlalchemy.engine import make_url


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-directory", required=True)
    parser.add_argument("--pattern", default="test_*.py")
    parser.add_argument("--test", action="append", help="Fully qualified unittest case; repeat to select several")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    data_dir = Path(args.data_directory).resolve()
    if not data_dir.is_relative_to((root / "tmp").resolve()):
        parser.error("The disposable data directory must be below app/tmp.")
    value = os.environ.get("HKR_HR_TEST_DATABASE_URL", "")
    if not value:
        parser.error("Set HKR_HR_TEST_DATABASE_URL for the disposable cluster.")
    url = make_url(value)
    if url.get_backend_name() != "postgresql" or url.host != "127.0.0.1" or url.database != "hkr_hr_db":
        parser.error("Only 127.0.0.1 PostgreSQL database hkr_hr_db is accepted.")
    conninfo = url.set(drivername="postgresql").render_as_string(hide_password=False)
    with psycopg.connect(conninfo) as conn:
        actual = Path(conn.execute("SHOW data_directory").fetchone()[0]).resolve()
        if actual != data_dir:
            parser.error("Server data_directory does not match the disposable target.")
    os.environ["DATABASE_URL"] = url.set(drivername="postgresql+psycopg").render_as_string(hide_password=False)
    os.environ["HKR_HR_ENV"] = "development"
    sys.path[:0] = [str(root), str(root / "tests")]
    import app
    original = app.create_app
    schemas = []

    def isolated(config=None):
        schema = "qa_" + uuid.uuid4().hex
        with psycopg.connect(conninfo, autocommit=True) as conn:
            conn.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
        schemas.append(schema)
        cfg = dict(config or {})
        cfg.update(SQLALCHEMY_DATABASE_URI=os.environ["DATABASE_URL"],
                   SQLALCHEMY_ENGINE_OPTIONS={"connect_args": {"options": "-csearch_path=" + schema}})
        return original(cfg)

    app.create_app = isolated
    try:
        suite = (unittest.defaultTestLoader.loadTestsFromNames(args.test) if args.test else
                 unittest.defaultTestLoader.discover(str(root / "tests"), pattern=args.pattern))
        result = unittest.TextTestRunner(verbosity=2).run(suite)
        return 0 if result.wasSuccessful() else 1
    finally:
        app.create_app = original
        # Remove only the schemas generated by this invocation on the verified cluster.
        with psycopg.connect(conninfo, autocommit=True) as conn:
            for schema in schemas:
                conn.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(schema)))


if __name__ == "__main__":
    raise SystemExit(main())
