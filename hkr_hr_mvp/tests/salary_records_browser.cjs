const {pdfBytes} = require('./pdf_fixture.cjs');
/* Synthetic localhost fixture only. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1600,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',async d=>d.accept('QA withdrawal'));
 try {
  await page.goto('http://127.0.0.1:8767/login');
  await page.locator('[name=username]').fill('admin');
  await page.locator('[name=password]').fill('test-admin-password');
  await Promise.all([page.waitForURL(u=>u.pathname!='/login'),page.locator('button[type=submit]').click()]);
  await page.goto('http://127.0.0.1:8767/salary-records?month=2026-04');
  const entity=await page.locator('select[name=entity_id] option').filter({hasText:'香港瑞沃工程有限公司'}).getAttribute('value');
  await page.locator('select[name=entity_id]').selectOption(entity);
  await page.locator('.salary-record-filters button').click();
  await page.waitForSelector('[data-salary-row]');
  const row=page.locator('[data-salary-row]').first();
  await row.locator('select[name$=".currency"]').selectOption('CNY');
  assert.equal(await row.locator('select[name$=".currency"]').inputValue(),'CNY');
  await row.locator('select[name$=".currency"]').selectOption('HKD');
  await row.locator('[data-money=gross_amount]').fill('12.345');
  await row.locator('[data-money=employee_mpf]').focus();
  assert.equal(await row.locator('[data-money=gross_amount]').inputValue(),'12.345');
  await row.locator('[data-money=gross_amount]').fill('10000');
  await row.locator('[data-money=employee_mpf]').fill('1500');
  assert.equal(await row.locator('[data-money=gross_amount]').inputValue(),'10,000.00');
  assert.equal(await row.locator('[data-money=net_amount]').inputValue(),'8,500.00');
  await row.locator('[data-money=net_amount]').fill('8,400.00');
  await row.locator('[data-money=gross_amount]').fill('10100');
  assert.equal(await row.locator('[data-money=net_amount]').inputValue(),'8,400.00');
  assert.match(await row.locator('.salary-record-difference').innerText(),/不一致/);
  await row.locator('summary').click();
  await row.locator('textarea').fill('QA net override; catch-up MPF');
  await row.locator('[type=file]').setInputFiles({name:'qa.pdf',mimeType:'application/pdf',buffer:pdfBytes('QA')});
  await row.locator('[data-money=net_amount]').fill('invalid');
  await page.locator('#salary-record-editor button[type=submit]').click();
  await page.waitForFunction(()=>document.getElementById('salary-record-message').textContent.includes('有效金額'));
  assert.equal(await row.locator('textarea').inputValue(),'QA net override; catch-up MPF');
  assert.equal(await row.locator('[type=file]').evaluate(el=>el.files.length),1);
  await row.locator('[data-money=net_amount]').fill('8,400.00');
  await Promise.all([page.waitForURL(u=>u.searchParams.get('month')==='2026-04',{waitUntil:'networkidle'}),page.locator('#salary-record-editor button[type=submit]').click()]);
  await page.waitForFunction(()=>document.body.textContent.includes('已保存 1 筆薪酬紀錄'));
  assert.equal(await page.locator('[data-money=net_amount]').first().inputValue(),'8,400.00');
  fs.mkdirSync('tmp/salary-record-qa',{recursive:true});
  await page.screenshot({path:'tmp/salary-record-qa/monthly.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.goto('http://127.0.0.1:8767/salary-records/annual?year=2026');
  await page.waitForSelector('table');
  assert.match(await page.locator('table').innerText(),/8,400\.00/);
  await page.screenshot({path:'tmp/salary-record-qa/annual.png',fullPage:true});
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'匯出 XLSX',exact:true}).click()]);
  await download.saveAs('tmp/salary-record-qa/browser-export.xlsx');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS: live browser default net, override, mismatch note, retained attachment/input on validation, CSRF save, layout, annual lookup, XLSX download; no JS errors.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
